// Numero PI

console.log(Math.PI);

// Numero Euler

console.log(Math.E);


// Redondear al entero mas cercano

console.log(Math.round(7.5));

// Redondear a la caja
console.log(Math.floor(7.9));

// Redonder al alza
console.log(Math.ceil(7.01));


// Numeros aleatorios

console.log(Math.round(Math.random() * 10));


// Valor absoluto

console.log(Math.abs(-27.9));

// Potencias

console.log(Math.pow(7, 7));

// Raix

console.log(Math.sqrt(7).toFixed(2));

// Minimo y maximo

console.log(Math.max(1, 7, 9, 29, 3));

console.log(Math.min(1, 7, 9, 29, 3));


// Más trigonometria, logaritmo, etc.

console.log(Math);

